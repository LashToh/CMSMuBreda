import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const LOCK_PATH = path.join(ROOT, 'server', 'data', '.installed');
const ENV_PATH = path.join(ROOT, '.env');

export function isInstalled() {
  return fs.existsSync(LOCK_PATH);
}

export function getInstallPaths() {
  return { root: ROOT, lockPath: LOCK_PATH, envPath: ENV_PATH };
}

export function markInstalled(meta = {}) {
  const payload = {
    at: new Date().toISOString(),
    ...meta,
  };
  fs.mkdirSync(path.dirname(LOCK_PATH), { recursive: true });
  fs.writeFileSync(LOCK_PATH, JSON.stringify(payload, null, 2), 'utf8');
}

/**
 * Write/merge .env keys. Does not print secrets.
 */
export function writeEnvFile(vars) {
  let existing = '';
  if (fs.existsSync(ENV_PATH)) {
    existing = fs.readFileSync(ENV_PATH, 'utf8');
  }

  const map = new Map();
  for (const line of existing.split(/\r?\n/)) {
    if (!line || line.trim().startsWith('#') || !line.includes('=')) continue;
    const i = line.indexOf('=');
    map.set(line.slice(0, i).trim(), line.slice(i + 1));
  }

  for (const [key, value] of Object.entries(vars)) {
    if (value === undefined || value === null) continue;
    map.set(key, String(value));
  }

  const lines = [
    '# Generated by CMSMuBreda /install — do not commit secrets',
    `# Updated ${new Date().toISOString()}`,
    '',
  ];
  for (const [key, value] of map.entries()) {
    lines.push(`${key}=${value}`);
  }
  fs.writeFileSync(ENV_PATH, `${lines.join('\n')}\n`, 'utf8');
}
